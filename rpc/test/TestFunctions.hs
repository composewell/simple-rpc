-- | Functions exported as RPC endpoints for the tests. The test executable
-- serves these endpoints when the environment variable
-- @SIMPLE_RPC_TEST_MODE@ is @server@.
--
module TestFunctions
    ( testVersion
    , rpcMap

    -- * Endpoints
    , echoInt
    , echoString
    , add
    , constant
    , three
    , printPartial
    , writeMarker
    , failing
    , replicateChar
    , valRpc
    ) where

import Control.Exception (ErrorCall(..), throwIO)
import System.IO (hPutStrLn, stderr)

import Simple.RPC

-- | The version reported by the test server.
testVersion :: String
testVersion = "test-1.0"

raw_echoInt :: Int -> IO Int
raw_echoInt = pure
$(rpcExport "raw_echoInt" "echoInt")

raw_echoString :: String -> IO String
raw_echoString = pure
$(rpcExport "raw_echoString" "echoString")

raw_add :: Int -> Int -> IO Int
raw_add x y = pure (x + y)
$(rpcExport "raw_add" "add")

raw_constant :: IO Int
raw_constant = pure 42
$(rpcExport "raw_constant" "constant")

raw_three :: Int -> String -> Bool -> IO (Int, String, Bool)
raw_three x y z = pure (x, y, z)
$(rpcExport "raw_three" "three")

-- | Print the argument to stdout without a trailing newline and a line to
-- stderr, return the argument.
raw_printPartial :: String -> IO String
raw_printPartial x = do
    putStr x
    hPutStrLn stderr "printPartial on stderr"
    pure x
$(rpcExport "raw_printPartial" "printPartial")

-- | Write the second argument to the file in the first argument.
raw_writeMarker :: FilePath -> Int -> IO Int
raw_writeMarker path x = do
    writeFile path "marker"
    pure x
$(rpcExport "raw_writeMarker" "writeMarker")

raw_failing :: Int -> IO Int
raw_failing _ = throwIO (ErrorCall "failing endpoint")
$(rpcExport "raw_failing" "failing")

raw_replicateChar :: Int -> Char -> IO String
raw_replicateChar n c = pure (replicate n c)
$(rpcExport "raw_replicateChar" "replicateChar")

-- | A function with the name of a variable used in the code generated by
-- 'rpcExport'.
val :: Int -> IO Int
val x = pure (x * 2)
$(rpcExport "val" "valRpc")

-- | The endpoints served by the test server.
rpcMap :: RpcMap IntermediateRep
rpcMap =
    createRpcMap
        [ evaluator echoInt
        , evaluator echoString
        , evaluator add
        , evaluator constant
        , evaluator three
        , evaluator printPartial
        , evaluator writeMarker
        , evaluator failing
        , evaluator replicateChar
        , evaluator valRpc
        ]
